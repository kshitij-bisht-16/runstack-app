type ContentStatus = 'pending' | 'approved'
type ViewMode = 'view' | 'edit'

/* ── Export Modal ── */
function ExportModal({ onClose }: { onClose: () => void }) {
  const options = [
    { icon: 'content_copy' as const, title: 'Copy to clipboard', desc: 'Paste anywhere instantly', highlight: true },
    { icon: 'download' as const, title: 'Download as .txt', desc: 'Plain text file', highlight: false },
    { icon: 'description' as const, title: 'Download as .docx', desc: 'Microsoft Word document', highlight: false },
  ]

  return (
    <div onClick={onClose} style={{
      position: 'fixed', inset: 0, background: 'rgba(0,0,0,0.6)',
      display: 'flex', alignItems: 'center', justifyContent: 'center', zIndex: 100,
    }}>
      <div onClick={(e) => e.stopPropagation()} style={{
        width: '420px', background: 'var(--bg-surface)', borderRadius: 'var(--radius-lg)',
        border: '1px solid var(--border-subtle)', padding: '28px', display: 'flex', flexDirection: 'column', gap: '20px',
      }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <h3 style={{ fontSize: '20px', fontWeight: 700, color: 'var(--text-primary)', fontFamily: "'Sora', sans-serif", margin: 0 }}>
            Export Content
          </h3>
          <button onClick={onClose} style={{ background: 'transparent', border: 'none', cursor: 'pointer' }}>
            <Icon name="close" size={20} color="var(--text-secondary)" />
          </button>
        </div>

        <div style={{ display: 'flex', flexDirection: 'column', gap: '8px' }}>
          {options.map((opt) => (
            <button
              key={opt.title}
              style={{
                display: 'flex', alignItems: 'center', gap: '14px',
                padding: '14px 16px', borderRadius: 'var(--radius-md)',
                background: opt.highlight ? 'var(--bg-hover)' : 'var(--bg-elevated)',
                border: opt.highlight ? '1px solid var(--border-default)' : '1px solid var(--border-subtle)',
                cursor: 'pointer', textAlign: 'left',
              }}
            >
              <Icon name={opt.icon} size={20} color="var(--text-secondary)" />
              <div>
                <div style={{ fontSize: '13px', fontWeight: 600, color: 'var(--text-primary)', fontFamily: "'Sora', sans-serif" }}>
                  {opt.title}
                </div>
                <div style={{ fontSize: '11px', color: 'var(--text-tertiary)', fontFamily: "'Sora', sans-serif" }}>
                  {opt.desc}
                </div>
              </div>
            </button>
          ))}
        </div>

        <Button variant="ghost" fullWidth onClick={onClose}>Cancel</Button>
      </div>
    </div>
  )
}

